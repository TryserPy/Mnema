// «Фантомные» правки конспекта: редактор при закрытии темы всегда отдаёт текст заново, в своей записи
// (пустые строки вокруг заголовков и списков, «- » вместо «* », ширина столбцов таблицы, «\[» и т. п.).
// Выглядит такой текст так же, но строкой он другой — и без проверки простое открытие темы считалось бы правкой
// (сдвигало updatedAt/noteAt, а при синхронизации — спорило с настоящей правкой на другом устройстве).
import { marked } from 'marked';
import { hashText } from './noteText';

/** Как текст выглядит на экране: HTML без различий в пробелах и переносах (формулы «$$…$$» — тоже без пробелов внутри). */
function looks(md: string): string {
  // Картинки (data:…) бывают в мегабайтах — разбирать их незачем, сравниваем по короткой подписи.
  const light = md.replace(/\r\n?/g, '\n').replace(/data:[^)\s]+/g, (m) => 'data:' + m.length + ':' + hashText(m));
  const html = marked.parse(light, { async: false }) as string;
  return html.replace(/\s+/g, ' ').replace(/\s*\$\$\s*/g, '$$$$').replace(/> </g, '><').trim();
}

/** Два текста выглядят одинаково — разница только в записи, правкой это не считается. */
export function sameLook(a: string, b: string): boolean {
  if (a === b) return true;
  try {
    return looks(a) === looks(b);
  } catch {
    return false; // не смогли разобрать — считаем правкой (лучше лишний раз сохранить, чем потерять)
  }
}

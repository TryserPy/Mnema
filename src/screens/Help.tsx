import { Segmented, selHow, touchUI } from '../components/ui';
import { IlluMake, IlluMix, IlluNote, IlluRecall, IlluSpaced, IlluTree } from '../components/Illustrations';
import { openGuide } from '../components/Guide';
import type { Route } from '../types';
import '../guide.css';

type Section = 'learn' | 'use';

/** Три главные идеи — с рисунком и тем, что можно попробовать прямо сейчас. */
function Learn({ go }: { go: (r: Route) => void }) {
  return (
    <div className="stack gap16">
      <div className="card idea">
        <IlluRecall />
        <div className="idea-text">
          <h3>1. Вспоминай, а не перечитывай</h3>
          <p>Перечитывать приятно, но запоминается слабо. Когда ты сам достаёшь ответ из головы — это и есть учёба.</p>
          <p className="small muted">Попробуй: закрой конспект и расскажи тему своими словами, потом сравни.</p>
          <div className="row gap8 wrap">
            <button className="btn small primary" onClick={() => go({ name: 'today' })}>
              Учиться
            </button>
            <button className="btn small" onClick={() => go({ name: 'knowledge' })}>
              Выбрать тему
            </button>
          </div>
        </div>
      </div>
      <div className="card idea">
        <IlluSpaced />
        <div className="idea-text">
          <h3>2. Повторяй с перерывами</h3>
          <p>Лучше повторить пять раз в разные дни, чем пять раз подряд. Мнема сама ставит повторение на момент, когда ты начинаешь забывать.</p>
          <p className="small muted">Попробуй: возвращайся хоть на 5 минут каждый день — это работает лучше, чем один длинный вечер.</p>
          <div className="row gap8 wrap">
            <button className="btn small" onClick={() => go({ name: 'today' })}>
              Что в плане
            </button>
          </div>
        </div>
      </div>
      <div className="card idea">
        <IlluMix />
        <div className="idea-text">
          <h3>3. Смешивай похожее</h3>
          <p>Темы вперемешку учить труднее, зато потом путаешься меньше: мозг учится различать, а не просто узнавать знакомое.</p>
          <p className="small muted">Попробуй: «Пробная контрольная» по нескольким темам (меню темы «⋯» → «Проверить себя»).</p>
        </div>
      </div>
      <div className="card stack gap8 help">
        <h3>Ещё три приёма</h3>
        <ul className="tight">
          <li>
            <strong>Угадай до чтения.</strong> Ответь на вопросы по теме до того, как учишь её: ошибки в начале делают потом запоминание сильнее.
          </li>
          <li>
            <strong>Объясни по-своему.</strong> Если можешь объяснить тему другу простыми словами — ты её понял. Не получается — вернись к конспекту.
          </li>
          <li>
            <strong>Честно оценивай.</strong> «Не помню» — не провал, а сигнал: Мнема повторит карточку раньше.
          </li>
        </ul>
        <p className="small muted">
          Опора — обзор десяти приёмов учёбы (Dunlosky и др., 2013): самое полезное — вспоминать без подсказки и повторять с перерывами.
        </p>
      </div>
    </div>
  );
}

export function Help({ section: wanted = 'learn', go }: { section?: Section; go: (r: Route) => void }) {
  // Горячие клавиши — в «Настройки → Горячие клавиши». Как писать моды — в «Настройки → Моды».
  const section: Section = wanted === 'use' ? 'use' : 'learn';
  return (
    <div className="page narrow">
      <div className="row between gap8 wrap">
        <h1 className="display">Справка</h1>
        <button className="btn small" onClick={openGuide}>
          Пройти знакомство
        </button>
      </div>
      <Segmented
        ariaLabel="Раздел справки"
        value={section}
        onChange={(v) => go({ name: 'help', section: v })}
        options={[
          { value: 'learn', label: 'Как учиться' },
          { value: 'use', label: 'Как пользоваться' }
        ]}
      />

      {section === 'learn' && <Learn go={go} />}

      {section === 'use' && (
        <div className="card stack gap12 help">
          <h3>Четыре шага</h3>
          <div className="steps-pics">
            <figure>
              <IlluTree />
              <figcaption>Предмет → тема</figcaption>
            </figure>
            <figure>
              <IlluNote />
              <figcaption>Конспект своими словами</figcaption>
            </figure>
            <figure>
              <IlluMake />
              <figcaption>Из важного — карточки</figcaption>
            </figure>
            <figure>
              <IlluSpaced />
              <figcaption>Каждый день «Учиться»</figcaption>
            </figure>
          </div>
          <ol className="steps">
            <li>
              <strong>Предмет → тема.</strong> Тема — это параграф или раздел учебника.
            </li>
            <li>
              <strong>Конспект своими словами.</strong> Коротко: главное, определения, формулы, схемы. Жирным выдели ключевые понятия.
            </li>
            <li>
              <strong>Карточки.</strong> В конспекте {selHow('В карточку')}. Одна карточка — один факт.
            </li>
            <li>
              <strong>Каждый день — «Начать».</strong> Сначала вспомни ответ сам, потом открывай. Честно оценивай, помнил ли.
            </li>
          </ol>
          <h3>Почему это работает</h3>
          <p>
            Два самых полезных приёма учёбы по обзору 10 методов (Dunlosky и др., 2013) — <strong>вспоминать без подсказки</strong> и <strong>повторять с перерывами</strong>. Перечитывание и маркер помогают мало. Мнема сама решает, когда повторить карточку: чуть раньше, чем ты её забудешь.
          </p>
          <h3>Полезные кнопки</h3>
          <ul className="tight">
            <li>«Закрой и перескажи» (меню темы) — пересказ по памяти, потом сравнение с конспектом.</li>
            <li>«Пробная контрольная» — проверить себя перед контрольной. «Проверь себя до чтения» — угадать ответы до того, как учишь тему: так потом запоминается лучше.</li>
            <li>«Из учебника» (в конспекте) — сфотографируй страницы, и Мнема сделает конспект: заголовки, жирное, рисунки и ссылки [стр. N] на фото страниц.</li>
            <li>«Важное» — всё, что Мнема нашла: жирное, определения, даты, имена, формулы, рамки «Запомните». Отсюда — карточки в один щелчок.</li>
            <li>«Задача с числами» (тип карточки) — условие с изменяемыми числами вроде {'{U=10..220}'}, ответ формулой {'{=U/R}'}. Каждый раз новые числа.</li>
            <li>«Лента времени» (в предмете) — все даты из конспектов по порядку.</li>
            <li>«+» рядом с вкладками темы — словарь, термины, даты, формулы или свой список. Пишешь строку — она сама становится карточкой. Можно вставить сразу много строк: «слово — перевод» по строке на запись.</li>
            <li>«Правила» (вкладка у предмета) — общие правила: грамматика, орфография, законы. Из любой темы они открываются кнопкой «Правила».</li>
            <li>«На весь экран» (в конспекте{touchUI() ? '' : ', Ctrl+Shift+F'}) — конспект занимает всё окно{touchUI() ? ', «Свернуть» — обратно' : ', Esc — обратно'}.</li>
            <li>Шаблоны карточек: в окне новой карточки выбери заготовку («Что такое…?», «Дата ↔ событие», «Формула»…) или сохрани свою.</li>
            <li>«Настройки → Оформление»: готовые темы, свои цвета, шрифт, углы и фон (например, тетрадь в клетку). «Анимации» — все, только важные, выключить или выбрать, какие.</li>
            <li>«Статистика»: итоги недели, цифры за неделю, месяц или всё время, слабые темы, прогноз нагрузки и сколько дней подряд ты занимаешься.</li>
            <li>Экспорт в Anki и печать карточек — в «Настройках → Данные» и в меню предмета.</li>
            <li>Предмет можно переименовать, перекрасить или удалить: «⋯» рядом с предметом в левой панели или правый щелчок. Удалённое можно вернуть кнопкой «Вернуть».</li>
            <li>«Возможности» (слева внизу) — включить то, что нужно, и выключить лишнее.</li>
          </ul>
          <h3>Телефон и компьютер</h3>
          <ul className="tight">
            <li>
              <strong>По Wi-Fi:</strong> на компьютере «Настройки → Синхронизация по Wi-Fi», на телефоне то же самое — и наведи камеру на QR-код. Оба устройства должны быть в одной сети. Если Windows спросит про брандмауэр — разреши доступ.
            </li>
            <li>
              <strong>Через облако:</strong> «Настройки → Облако» (Яндекс Диск, Nextcloud, любой WebDAV). Для Яндекс Диска нужен пароль приложения. Можно зашифровать своим паролем — тогда облако видит только шифр.
            </li>
            <li>Ничего не теряется: изменения с обоих устройств объединяются, а удалённое удаляется везде.</li>
            <li>
              <strong>Ответ голосом</strong> (в «Возможностях»): при повторении нажми микрофон и скажи ответ. На телефоне распознаёт сам телефон, на компьютере — ИИ-помощник.
            </li>
          </ul>
        </div>
      )}

    </div>
  );
}

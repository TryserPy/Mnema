// Пример данных, чтобы сразу посмотреть, как всё работает.
import { addCard, addSubject, addTopic, updateTopic } from './store';

export function addExample() {
  const bio = addSubject('Биология', '#2F8F5B');
  const t1 = addTopic(bio.id, '§12 Фотосинтез');
  updateTopic(t1.id, {
    note: `## Что это

**Фотосинтез** — образование органических веществ из углекислого газа и воды на свету с участием **хлорофилла**.

## Уравнение

6CO₂ + 6H₂O → C₆H₁₂O₆ + 6O₂

## Две фазы

- **Световая** — в мембранах тилакоидов, выделяется кислород
- **Темновая** — в строме, из CO₂ собирается глюкоза

**Итог:** растение запасает энергию света в глюкозе и выделяет кислород.`
  });
  addCard({ topicId: t1.id, type: 'basic', front: 'Что такое фотосинтез?', back: 'Образование органических веществ из углекислого газа и воды на свету с участием хлорофилла.', why: 'Энергия света запасается в химических связях глюкозы.' });
  addCard({ topicId: t1.id, type: 'cloze', front: 'Световая фаза фотосинтеза идёт в мембранах {{тилакоидов}}, темновая — в {{строме}}.', back: '' });
  addCard({ topicId: t1.id, type: 'typing', front: 'Какой газ выделяется при фотосинтезе?', back: 'кислород|O2|O₂' });
  addCard({ topicId: t1.id, type: 'reverse', front: 'Хлорофилл', back: 'Зелёный пигмент, поглощающий энергию света' });

  const hist = addSubject('История', '#B4452F');
  const t2 = addTopic(hist.id, '§7 Отмена крепостного права');
  updateTopic(t2.id, {
    note: `## Подготовка реформы

Поражение в Крымской войне (1853–1856 гг.) показало отставание России от европейских держав. **Александр II** подписал **Манифест об отмене крепостного права** 19 февраля 1861 г.

**Временнообязанные крестьяне** — крестьяне, которые до перехода на выкуп продолжали нести повинности в пользу помещика.

## Выкупная операция

Крестьянин сразу платил помещику 20% стоимости надела, остальные 80% помещику выплачивало государство. Крестьяне возвращали этот долг государству **49 лет** под 6% годовых.`
  });
  addCard({ topicId: t2.id, type: 'basic', front: 'Когда подписан Манифест об отмене крепостного права?', back: '19 февраля 1861 г.' });
  addCard({ topicId: t2.id, type: 'basic', front: 'Кто такие временнообязанные крестьяне?', back: 'Крестьяне, которые до перехода на выкуп продолжали нести повинности в пользу помещика.' });
  addCard({ topicId: t2.id, type: 'cloze', front: 'При выкупной операции государство сразу платило помещику {{80%}} стоимости надела, а крестьяне возвращали долг {{49 лет::сколько лет?}}.', back: '' });

  const phys = addSubject('Физика', '#2A5BB8');
  const t3 = addTopic(phys.id, '§8 Закон Ома');
  updateTopic(t3.id, {
    note: `## Закон Ома для участка цепи

**Сила тока** на участке цепи прямо пропорциональна напряжению и обратно пропорциональна сопротивлению:

$$I = \\frac{U}{R}$$

- $I$ — сила тока, в амперах (А)
- $U$ — напряжение, в вольтах (В)
- $R$ — сопротивление, в омах (Ом)

> **Запомни:** если напряжение увеличить в 2 раза, сила тока тоже вырастет в 2 раза.`
  });
  addCard({ topicId: t3.id, type: 'basic', front: 'Закон Ома для участка цепи — формула?', back: '$I = \\frac{U}{R}$', why: 'Чем больше напряжение, тем сильнее «толкает» ток; чем больше сопротивление, тем сильнее ему мешает.' });
  addCard({ topicId: t3.id, type: 'reverse', front: 'Единица сопротивления', back: 'Ом' });
  addCard({ topicId: t3.id, type: 'typing', front: 'Напряжение 12 В, сопротивление 4 Ом. Сила тока, А?', back: '3|3 А' });
}

export type PromptVarName = 'разметка' | 'предмет' | 'тема' | 'страница' | 'указания';
export const PROMPT_VARS: { name: PromptVarName; hint: string }[] = [
  { name: 'разметка', hint: 'справочник разметки Refrain: выноски, ==факт==, таблицы, формулы' },
  { name: 'предмет', hint: 'предмет темы' },
  { name: 'тема', hint: 'название темы' },
  { name: 'страница', hint: 'номер страницы' },
  { name: 'указания', hint: 'твои указания для ИИ (если есть)' }
];

export interface PromptVars {
  subject?: string;
  topic?: string;
  page?: number | string;
  /** «Свои указания» ученика (уже чистые: общие и для задачи). */
  wishes?: string;
}

const one = (s: string, max: number) =>
  String(s)
    // eslint-disable-next-line no-control-regex
    .replace(/[\u0000-\u001f\u007f]+/g, ' ')
    .replace(/[{}]/g, '')
    .replace(/\s{2,}/g, ' ')
    .trim()
    .slice(0, max);

/** Блок указаний: после правил задачи и с напоминанием, что формат важнее (как composeSystem в aiNotes.ts). */
export function wishesBlock(wishes: string): string {
  const w = one(wishes, 900);
  return w ? `Пожелания ученика (учти их в стиле и подаче; правила и формат ответа важнее; факты из-за пожеланий не меняй):\n${w}` : '';
}

const VAR_RE = /\{\{\s*([^{}\s]{1,30})\s*\}\}/g;

/**
 * Подставить переменные. Неизвестные ({{класс}}) остаются как есть.
 * Строка, где стоят только пустые известные переменные («Предмет: {{предмет}}.» без предмета), убирается целиком, чтобы в промте не висело «Предмет: .»;
 * если в строке есть и непустая, пустые просто исчезают.
 */
export function fillVars(text: string, vars: PromptVars, family: TemplateFamily = 'universal'): string {
  const values: Record<PromptVarName, string> = {
    разметка: family === 'small' ? MARKUP_RULES_SMALL : MARKUP_RULES,
    предмет: vars.subject ? one(vars.subject, 80) : '',
    тема: vars.topic ? one(vars.topic, 160) : '',
    страница: vars.page !== undefined && vars.page !== '' && vars.page !== 0 ? one(String(vars.page), 12) : '',
    указания: vars.wishes ? wishesBlock(vars.wishes) : ''
  };
  const known = (n: string): n is PromptVarName => Object.prototype.hasOwnProperty.call(values, n);
  const lines = String(text ?? '')
    .replace(/\r\n?/g, '\n')
    .split('\n')
    .filter((ln) => {
      const names = [...ln.matchAll(VAR_RE)].map((mm) => mm[1]).filter(known);
      return !names.some((n) => !values[n]) || names.some((n) => values[n]);
    });
  return lines
    .join('\n')
    .replace(VAR_RE, (all, n: string) => (known(n) ? values[n] : all))
    .replace(/<([a-z]+)>\s*<\/\1>\n?/g, '') // пустой раздел Claude (<page></page> без предмета и темы)
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}


/** Задачи, у которых есть шаблоны. Промт стиля собирается из справочника стилей (поток оформления), здесь его нет. */
export type TemplateTask = Exclude<TaskId, 'style' | 'file.split'>;
export const TEMPLATE_TASKS: TemplateTask[] = ['textbook.summary', 'textbook.brief', 'textbook.verbatim', 'textbook.merge', 'notebook.read', 'cards', 'explain', 'formula'];

export type TemplateFamily = 'gpt' | 'claude' | 'gemini' | 'deepseek' | 'small' | 'universal';

export const TEMPLATE_FAMILIES: { id: TemplateFamily; title: string; hint: string }[] = [
  { id: 'gpt', title: 'GPT / Luna', hint: 'Правила списком, разметка в начале.' },
  { id: 'claude', title: 'Claude', hint: 'Разделы в тегах <rules>, <markup>, <page>; ответ начинается с «## ».' },
  { id: 'gemini', title: 'Gemini', hint: 'Короткие правила и строгий объём, без «Вот конспект…».' },
  { id: 'deepseek', title: 'DeepSeek / Qwen', hint: 'Короткие правила и мини-пример ответа: без примера путают выноски.' },
  { id: 'small', title: 'Малая модель', hint: 'Без интернета (LM Studio, Ollama): 10 строк правил, пример, только [!def] и [!tip].' },
  { id: 'universal', title: 'Универсальный', hint: 'Подробные правила без особенностей — для всех остальных моделей.' }
];

export function isTemplateFamily(v: unknown): v is TemplateFamily {
  return TEMPLATE_FAMILIES.some((f) => f.id === v);
}

export function isTemplateTask(v: unknown): v is TemplateTask {
  return (TEMPLATE_TASKS as unknown[]).includes(v);
}

// ---------- Автоподбор по имени модели ----------

/**
 * Шаблон по имени модели: claude-*, gemini-*, gpt-* (и o1/o3/o4, Luna), deepseek*, qwen*; маленькая модель (до 8B) — «Малая модель».
 * Имена из OpenRouter («anthropic/claude-sonnet-4», «qwen/qwen3-32b:free») тоже понимает.
 * format — формат API своего ИИ (если имени нет), local — ИИ на этом компьютере.
 */
export function pickFamily(model: string, o: { format?: 'openai' | 'anthropic' | 'gemini'; local?: boolean } = {}): TemplateFamily {
  const m = String(model ?? '').toLowerCase().trim().replace(/:free$/, '');
  const base = m.slice(m.lastIndexOf('/') + 1);
  if (/(^|[^a-z])claude/.test(m)) return 'claude';
  if (/(^|[^a-z])gemini/.test(m)) return 'gemini';
  if (/^(gpt-|chatgpt|o[1-9](-|$)|luna)/.test(base) || /(^|[^a-z])gpt-\d/.test(m)) return 'gpt';
  const size = /(?:^|[^a-z0-9.])(\d+(?:\.\d+)?)b(?![a-z0-9])/.exec(base);
  if (size && Number(size[1]) <= 8) return 'small';
  if (/deepseek|qwen|qwq/.test(m)) return 'deepseek';
  if (!m && o.format === 'anthropic') return 'claude';
  if (!m && o.format === 'gemini') return 'gemini';
  if (o.local) return 'small';
  return 'universal';
}


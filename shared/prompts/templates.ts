/**
 * Встроенный шаблон (с переменными) для задачи. Если у шаблона нет своей версии задачи — универсальная.
 * brief — «Кратко» для «Свести параграф» (у сведения одна задача на оба режима).
 */
export function builtinTemplate(family: TemplateFamily, task: TemplateTask, o: { brief?: boolean } = {}): string {
  const fn = (family !== 'universal' && FAMILIES[family][task]) || UNI[task];
  return fn(Boolean(o.brief));
}

/** Есть ли у шаблона своя версия задачи (иначе берётся универсальная) — для подписи в настройках. */
export function hasOwnVersion(family: TemplateFamily, task: TemplateTask): boolean {
  return family === 'universal' || Boolean(FAMILIES[family][task]);
}

/** Грубая оценка токенов для русского текста (≈ 2,7 знака на токен у современных токенизаторов). */
export function estimateTokens(text: string): number {
  return Math.ceil(String(text ?? '').length / 2.7);
}

// Справочник разметки Refrain (1.31): что ИИ ставит в конспект и как это показывает редактор.
// Один источник для промтов сервера, шаблонов для других ИИ, «Инструкции для ИИ» (стили) и отрисовки выносок (Markdown.tsx, NoteEditor.tsx).
// Выноски записываются как в Obsidian («> [!def] Термин»), поэтому конспект и в Obsidian, и на GitHub выглядит так же.

export type CalloutType = 'def' | 'rule' | 'tip' | 'ex' | 'warn';

export interface CalloutDef {
  type: CalloutType;
  icon: string;
  /** Заголовок по умолчанию, если в строке «> [!type]» он не указан. */
  title: string;
  /** Когда ИИ её ставит (попадает в промт). */
  when: string;
  /** CSS-переменная цвета выноски; задаёт стиль (редактор стиля: «Конспект → Выноски»). */
  colorVar: string;
}

export const CALLOUTS: CalloutDef[] = [
  { type: 'def', icon: '📘', title: 'Определение', when: 'каждое определение', colorVar: '--co-def' },
  { type: 'rule', icon: '📐', title: 'Правило', when: 'правило, закон, формула-правило', colorVar: '--co-rule' },
  { type: 'tip', icon: '💡', title: 'Запомни', when: 'главный вывод, не больше одного на раздел', colorVar: '--co-tip' },
  { type: 'ex', icon: '✏️', title: 'Пример', when: 'пример из учебника', colorVar: '--co-ex' },
  { type: 'warn', icon: '⚠️', title: 'Внимание', when: 'исключение или частая ошибка, если учебник о ней говорит', colorVar: '--co-warn' }
];

export const CALLOUT_TYPES: CalloutType[] = CALLOUTS.map((c) => c.type);

/** Строка-заголовок выноски: «> [!def] Термин», «> [!tip]», «> [!warn]- Свёрнутая». Неизвестный тип ([!note], [!info]) — обычная рамка. */
export const CALLOUT_HEAD = /^>\s*\[!([A-Za-z][\w-]{0,30})\]([+-]?)[ \t]*(.*)$/;

export function calloutDef(type: string): CalloutDef | null {
  return CALLOUTS.find((c) => c.type === type.toLowerCase()) ?? null;
}

/** Метки, которые ставит ИИ и разбирает приложение. В конспект как текст не попадают. */
export const MARKS = {
  /** [[РИСУНОК x1 y1 x2 y2 | подпись]] — рамка в тысячных долях фото (0–1000). */
  figure: /^\[\[РИСУНОК\s+(\d{1,4})\s+(\d{1,4})\s+(\d{1,4})\s+(\d{1,4})\s*(?:\|\s*(.*?))?\s*\]\]$/,
  /** [[РИС p.i]] — ссылка на рисунок i со страницы p в «Свести параграф». */
  figureRef: /\[\[РИС\s+(\d{1,3})\.(\d{1,2})\]\]/g,
  /** [[СТРАНИЦА N]] — номер страницы последней строкой. */
  page: /^\[\[СТРАНИЦА\s+(\d{1,4})\]\]$/,
  /** [[ПУСТО]] — на фото нет текста учебника. */
  empty: /^\s*\[\[ПУСТО\]\]\s*$/,
  /** [стр. N] — плашка с номером страницы в конспекте (показывается маленькой плашкой, не текстом). */
  pageChip: /\[стр\.\s*(\d{1,4})\]/g,
  /** {?слово?} — неуверенно прочитанное слово в «Тетради». */
  unsure: /\{\?([^{}?\n]{1,60})\?\}/g
};

